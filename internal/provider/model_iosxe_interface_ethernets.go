// fromBodyXML reads every item that exists below the parent path. It is used after an import, where
// the set of items is not known upfront.
func (data *InterfaceEthernets) fromBodyXML(ctx context.Context, res xmldot.Result) {
	data.Items = make(map[string]InterfaceEthernetsItems)
	keyNames := []string{"name"}
	for _, element := range []string{"GigabitEthernet", "TwoGigabitEthernet", "FiveGigabitEthernet", "TenGigabitEthernet", "TwentyFiveGigE", "FortyGigabitEthernet", "FiftyGigabitEthernet", "HundredGigE", "TwoHundredGigE", "FourHundredGigE"} {
		for _, keyValues := range helpers.ListXPathKeys(res, "data"+data.getXPath(), element, keyNames) {
			keyValues = append([]string{element}, keyValues...)
			key := strings.Join(keyValues, ";")
			single := data.toSingle(key, InterfaceEthernetsItems{})
			single.fromBodyXML(ctx, res)
			data.Items[key] = data.toItem(single)
		}
	}
}

