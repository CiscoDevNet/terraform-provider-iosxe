func (data InterfaceEthernets) toBodyXML(ctx context.Context, config InterfaceEthernets) string {
	body := netconf.Body{}
	for _, key := range data.itemKeys() {
		body = data.toSingle(key, data.Items[key]).addToBodyXML(ctx, data.toSingle(key, config.Items[key]), body)
	}
	bodyString, err := body.String()
	if err != nil {
		tflog.Error(ctx, fmt.Sprintf("Error converting body to string: %s", err))
	}
	return bodyString
}

