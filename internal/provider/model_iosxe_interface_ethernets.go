func (data *InterfaceEthernets) addDeletedItemsXML(ctx context.Context, state InterfaceEthernets, body string) string {
	for _, key := range state.itemKeys() {
		stateSingle := state.toSingle(key, state.Items[key])
		if planItem, ok := data.Items[key]; ok {
			planSingle := data.toSingle(key, planItem)
			body = planSingle.addDeletedItemsXML(ctx, stateSingle, body)
			continue
		}
		// The whole item was removed from the map
		// The object itself cannot be deleted, so only its attributes are removed
		body = stateSingle.addDeletePathsXML(ctx, body)
	}
	return body
}

