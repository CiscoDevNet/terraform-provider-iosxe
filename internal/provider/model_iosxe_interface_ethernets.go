func (data *InterfaceEthernets) updateFromBodyXML(ctx context.Context, res xmldot.Result) {
	for _, key := range data.itemKeys() {
		single := data.toSingle(key, data.Items[key])
		// Drop items that no longer exist on the device
		if !helpers.GetFromXPath(res, "data"+single.getXPath()).Exists() {
			delete(data.Items, key)
			continue
		}
		single.updateFromBodyXML(ctx, res)
		data.Items[key] = data.toItem(single)
	}
}

